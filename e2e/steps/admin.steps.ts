import { expect } from "@playwright/test";
import { createBdd } from "playwright-bdd";
import { test } from "./fixtures";
import { e2eWorld, uniqueLabel } from "./world";

const { When, Then } = createBdd(test);

When("I create a published parish notice", async ({ page }) => {
  await page.goto("/admin/avisos");
  e2eWorld.lastNoticeTitle = uniqueLabel("Notice");
  await page.getByPlaceholder("Título").fill(e2eWorld.lastNoticeTitle);
  await page.getByPlaceholder("Texto (pode usar HTML simples)").fill("<p>E2E test content.</p>");
  await page.getByRole("button", { name: "Cadastrar aviso" }).click();
  await expect(page.getByRole("status")).toContainText(/Cadastro realizado/i, { timeout: 20_000 });
});

When("I create a published news post", async ({ page }) => {
  await page.goto("/admin/noticias");
  e2eWorld.lastPostTitle = uniqueLabel("News");
  const slug = `e2e-${Date.now()}`;
  await page.getByPlaceholder("Título").fill(e2eWorld.lastPostTitle);
  await page.getByPlaceholder("slug-opcional").fill(slug);
  await page.getByPlaceholder("Resumo").fill("Summary generated by E2E test.");
  await page.getByPlaceholder("Conteúdo (HTML)").fill("<p>E2E news body.</p>");
  await page.locator("form").filter({ hasText: "Nova notícia" }).getByRole("checkbox").check();
  await page.getByRole("button", { name: "Cadastrar notícia" }).click();
  await expect(page.getByRole("status")).toContainText(/Cadastro realizado/i, { timeout: 20_000 });
});

When("I create a mass location", async ({ page }) => {
  await page.goto("/admin/horarios");
  e2eWorld.lastMassLocationName = uniqueLabel("Chapel E2E");
  await page.getByPlaceholder("Nome (ex.: Matriz Paroquial)").fill(e2eWorld.lastMassLocationName);
  await page.getByPlaceholder("Endereço completo").fill("Rua Teste, 1 — São Paulo");
  await page.getByPlaceholder(/Quinta-feira/).fill("Domingo: 10h");
  await page.getByRole("button", { name: "Cadastrar local" }).click();
  await expect(page.getByRole("status")).toContainText(/Cadastro realizado/i, { timeout: 20_000 });
});

When("I open admin {string} management", async ({ page }, section: string) => {
  const map: Record<string, string> = {
    candles: "/admin/velas",
    raffles: "/admin/rifas",
    "site info": "/admin/informacoes",
    "online rosary": "/admin/terco-online",
  };
  const href = map[section.toLowerCase()];
  if (!href) throw new Error(`Unknown admin section: ${section}`);
  await page.goto(href);
});

Then("I should see the candles admin page", async ({ page }) => {
  await expect(page.getByRole("heading", { name: /Velas virtuais/i })).toBeVisible();
});

Then("I should see the raffles list in admin", async ({ page }) => {
  await expect(page.getByRole("heading", { name: "Rifas dos Santos" })).toBeVisible();
  await expect(page.getByRole("link", { name: "Nova rifa" })).toBeVisible();
});

Then("I should see the general information form", async ({ page }) => {
  await expect(page.getByRole("heading", { name: "Informações gerais do site" })).toBeVisible();
});

Then("I should see the online rosary schedule form", async ({ page }) => {
  await expect(page.getByText(/Terço online/i).first()).toBeVisible();
});

Then("the news post should appear on the public news page", async ({ page }) => {
  await page.goto("/noticias");
  await expect(page.getByText(e2eWorld.lastPostTitle)).toBeVisible({ timeout: 20_000 });
});

Then("the mass location should appear on the schedule page", async ({ page }) => {
  await page.goto("/horarios");
  await expect(page.getByText(e2eWorld.lastMassLocationName)).toBeVisible({ timeout: 20_000 });
});

When("I light a virtual candle in free mode", async ({ page }) => {
  await page.goto("/velas");
  await page.locator('input[name="donorName"]').scrollIntoViewIfNeeded();
  await page.locator('input[name="donorName"]').fill("E2E Participant");
  await page.locator('input[name="intention"]').fill("Automated test intention");
  await page.getByRole("button", { name: /Acender vela gratuitamente/i }).click();
  await page.waitForURL(/\/velas\/sucesso/, { timeout: 30_000 });
});

Then("I should see candle success confirmation", async ({ page }) => {
  await expect(page).toHaveURL(/\/velas\/sucesso/);
});
