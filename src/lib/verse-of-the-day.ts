const PARISH_TIME_ZONE = "America/Sao_Paulo";

/** Dia civil em São Paulo, para o versículo não virar à meia-noite de outro fuso. */
export function parishCalendarDay(date = new Date()) {
  const formatted = new Intl.DateTimeFormat("en-CA", {
    timeZone: PARISH_TIME_ZONE,
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).format(date);
  const [year, month, day] = formatted.split("-").map(Number);
  return { year, month, day };
}

export function verseForDate(date = new Date()): DailyVerse {
  const { year, month, day } = parishCalendarDay(date);
  const dayNumber = Math.floor(Date.UTC(year, month - 1, day) / 86_400_000);
  const index = ((dayNumber % DAILY_VERSES.length) + DAILY_VERSES.length) % DAILY_VERSES.length;
  return DAILY_VERSES[index]!;
}
